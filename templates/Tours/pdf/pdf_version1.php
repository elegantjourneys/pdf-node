    <h2 style="font-size:18px; margin:8px 0; border-bottom:3px solid #dcdcdc; padding-bottom:6px; text-transform:uppercase;">Detailed Programme — Pre-Conference Tour</h2>

    <!-- Day block (repeatable) -->
    <div style="margin-top:14px;">
      <h3 style="font-size:15px; margin:6px 0; color:#003366;">DAY 01: DELHI — AGRA</h3>
      <p style="margin:6px 0; font-size:13px; line-height:1.5;">
        Morning: Drive by surface to Agra (approx. 203 Kms / 4 hrs). On arrival check in at your hotel and relax. Late afternoon proceed for visit to Agra Fort. Also visit the Taj Mahal (closed on Fridays). Overnight at hotel.
      </p>
      <p style="margin:6px 0; font-size:13px;"><strong>Meals:</strong> Breakfast</p>
    </div>

    <div style="margin-top:14px;">
      <h3 style="font-size:15px; margin:6px 0; color:#003366;">DAY 02: AGRA — FATEHPUR SIKRI — JAIPUR</h3>
      <p style="margin:6px 0; font-size:13px; line-height:1.5;">
        After breakfast check out and drive to Jaipur via Fatehpur Sikri (approx. 250 Kms / 7 hrs). Visit Fatehpur Sikri and en-route photo stop at Chand Baori stepwell. Arrival in Jaipur and hotel check in. Overnight at hotel.
      </p>
      <p style="margin:6px 0; font-size:13px;"><strong>Meals:</strong> Breakfast</p>
    </div>

    <div style="margin-top:14px;">
      <h3 style="font-size:15px; margin:6px 0; color:#003366;">DAY 03: JAIPUR (SIGHTSEEING)</h3>
      <p style="margin:6px 0; font-size:13px; line-height:1.5;">
        After breakfast proceed for excursion to Amber Fort with photo stops at Hawa Mahal (Palace of Winds). Continue city sightseeing to City Palace, Jantar Mantar and local bazaars. Overnight at hotel.
      </p>
      <p style="margin:6px 0; font-size:13px;"><strong>Meals:</strong> Breakfast</p>
    </div>

    <div style="margin-top:14px;">
      <h3 style="font-size:15px; margin:6px 0; color:#003366;">DAY 04: JAIPUR — GOA</h3>
      <p style="margin:6px 0; font-size:13px; line-height:1.5;">
        Morning at leisure. Transfer to airport to connect flight for Goa (via Mumbai). On arrival transfer to hotel and relax. Overnight at hotel.
      </p>
      <p style="margin:6px 0; font-size:13px;"><strong>Meals:</strong> Breakfast</p>
    </div>

    <div style="margin-top:14px;">
      <h3 style="font-size:15px; margin:6px 0; color:#003366;">DAY 05 — DAY 06: GOA</h3>
      <p style="margin:6px 0; font-size:13px; line-height:1.5;">
        Day 05: Morning after breakfast proceed for short tour of Goa visiting Se Cathedral, Basilica of Bom Jesus and other heritage sites. Remainder of day at leisure.
        <br>
        Day 06: Full day free to relax or enjoy water sports / beach activities. Overnight at hotel.
      </p>
      <p style="margin:6px 0; font-size:13px;"><strong>Meals:</strong> Breakfast</p>
    </div>

    <div style="margin-top:14px;">
      <h3 style="font-size:15px; margin:6px 0; color:#003366;">DAY 07: GOA — DELHI — DEPARTURE</h3>
      <p style="margin:6px 0; font-size:13px; line-height:1.5;">
        Morning at leisure; later transfer to airport for flight to Delhi and onward departure. Assistance on arrival for international connections as required. End of tour.
      </p>
      <p style="margin:6px 0; font-size:13px;"><strong>Meals:</strong> Breakfast</p>
    </div>

